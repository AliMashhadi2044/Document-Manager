import { useEffect, useState } from 'react';

/**
 * مقداری که با تأخیر، آخرین تغییر را می‌پذیرد.
 *
 * چرا لازم است: هر فیلد جست‌وجو و هر مقدار فیلتر، مستقیم به کلید کوئری می‌رود و
 * هر نویسهٔ تایپ‌شده یک درخواست می‌سازد. نوشتن «محمدی» یعنی شش درخواست، که پنج‌تایش
 * پیش از رسیدن پاسخ بی‌مصرف شده‌اند. روی گزارشی که چند صد هزار سند را می‌پیماید،
 * همین پنج درخواست هزینهٔ واقعی دارند — نه فقط برای سرور، که برای خود کاربر هم:
 * نتیجهٔ درخواستِ کُندِ قدیمی ممکن است دیرتر برسد و جای نتیجهٔ درست بنشیند.
 *
 * **مقایسه با `Object.is` است**، پس برای شیء و آرایه باید مرجع پایدار باشد
 * (`useMemo`) وگرنه تأخیر هر بار از نو شروع می‌شود و مقدار هیچ‌وقت ته‌نشین نمی‌شود.
 *
 * مقدار اول **بی‌تأخیر** برمی‌گردد: بارگذاری نخست صفحه نباید نیم‌ثانیه خالی بماند.
 */
export function useDebouncedValue<T>(value: T, delay = 300): T {
  const [settled, setSettled] = useState(value);

  /*
    مقایسه داخل `setSettled` انجام می‌شود، نه بیرونِ effect: این‌طور `settled` لازم
    نیست در فهرست وابستگی‌ها باشد. اگر بود، با هر نشستنِ مقدار، همین effect دوباره
    اجرا می‌شد و تایمر تازه‌ای می‌ساخت که کاری جز نشاندن همان مقدار نداشت.
  */
  useEffect(() => {
    const timer = setTimeout(
      () => setSettled((current) => (Object.is(current, value) ? current : value)),
      delay,
    );
    return () => clearTimeout(timer);
  }, [value, delay]);

  return settled;
}
