-- مجموعه خریدار پیش‌فرض.
--
-- در فرم ایجاد سند، این مجموعه از پیش انتخاب می‌شود. چون در عمل همیشه یکی از
-- مجموعه‌ها غالب است، نبودنش یعنی کاربر هر بار یک انتخاب تکراری انجام می‌دهد.

ALTER TABLE "buyer_entities"
  ADD COLUMN "is_default" BOOLEAN NOT NULL DEFAULT false;

-- حداکثر یک مجموعه پیش‌فرض در کل جدول.
--
-- این قاعده در **پایگاه داده** گذاشته می‌شود، نه فقط در سرویس: دو درخواست هم‌زمان
-- که هر دو یک مجموعه را پیش‌فرض می‌کنند، با بررسی در کد از هم بی‌خبرند و دو ردیف
-- پیش‌فرض می‌سازند. ایندکس جزئی یکتا، همان حالت را در سطح تراکنش رد می‌کند.
CREATE UNIQUE INDEX "buyer_entities_one_default_uk"
  ON "buyer_entities" ((true))
  WHERE "is_default" = true;
