/**
 * سیاست رمز عبور.
 *
 * یک جا نوشته می‌شود و هر دو طرف همان را می‌خوانند: سرور **اعمالش** می‌کند و رابط
 * همان متن را به کاربر نشان می‌دهد. اگر هر طرف قاعدهٔ خودش را داشت، کاربر رمزی
 * می‌ساخت که رابط قبول می‌کرد و سرور رد — یا بدتر، برعکس.
 *
 * قاعده‌ها عمداً کم‌اند و همان‌هایی که NIST SP 800-63B توصیه می‌کند: **طول** مهم‌ترین
 * عامل است. الزام نویسهٔ خاص و تغییر دوره‌ای رمز، کاربر را به الگوهای حدس‌پذیر
 * (`Password1!`) می‌راند و امنیت واقعی نمی‌افزاید.
 */

export const PASSWORD_MIN_LENGTH = 12;
export const PASSWORD_MAX_LENGTH = 200;

export const PASSWORD_POLICY_HINT =
  'رمز عبور باید دست‌کم ۱۲ نویسه باشد و فقط از عدد یا فقط از یک نویسهٔ تکراری ساخته نشده باشد.';

/**
 * ایرادِ یک رمز، یا `null` وقتی قابل قبول است.
 *
 * رمزهای بسیار حدس‌پذیر — همه‌عدد، یا یک نویسهٔ تکرارشده — رد می‌شوند؛ این‌ها همان
 * چیزی‌اند که کاربر وقتی فقط «۱۲ نویسه» می‌شنود می‌نویسد (`123456789012`).
 */
export function passwordPolicyIssue(password: string): string | null {
  if (password.length < PASSWORD_MIN_LENGTH) {
    return `رمز عبور باید دست‌کم ${PASSWORD_MIN_LENGTH} نویسه باشد`;
  }
  if (password.length > PASSWORD_MAX_LENGTH) {
    return `رمز عبور نمی‌تواند بیش از ${PASSWORD_MAX_LENGTH} نویسه باشد`;
  }
  if (/^\d+$/u.test(password)) {
    return 'رمز عبور نمی‌تواند فقط از رقم ساخته شود';
  }
  if (new Set(password).size < 4) {
    return 'رمز عبور بیش از حد تکراری است';
  }
  return null;
}
